export const cardById = new Map(CARDS.map((c) => [c.id, c]));

// the card whose stem fits the word best (exact words first, then the longest stem), or null
export function cardFor(word) {
  const w = word.toLowerCase().replace(/ё/g, 'ё');
  let best = null, len = 0;
  for (const c of CARDS) for (const s of c.w) {
    const n = s[0] === '=' ? (w === s.slice(1) ? 1e3 : 0) : (w.startsWith(s) ? s.length : 0);
    if (n > len) { best = c; len = n; }
  }
  return best;
}
