export const POEMS = `
# sh | autumn | kids | Тыква
Осень. Тыкву тянет Маша,
Тянут мама, Паша, Даша.
Тянут-тянут — ни на шаг!
Тыква с места — ну никак!
Тянет кошка, тянет мышка —
Ух! — и тыква! Вот так пышка!
Будет тыквенная каша.
Кушай, мышка! Кушай, Маша!

# sh | winter | cat | Шапка
Маша шапку надевает —
Шапка «мяу!» напевает.
Ой, а в шапке — кошка Мушка!
Шапка Мушке — как подушка.
Тише, Маша, погоди,
Мушку в шапке не буди!
Маша — в шубе и в панаме —
Машет папе, машет маме.

# sh | autumn | animals | Шишка
Ходит мишка по опушке.
Бух! — и шишка на макушке!
— Ой! Откуда эта шишка? —
Тихо охнет бедный мишка.
Мишка шишку в шапку — хоп!
И домой: топ-топ, топ-топ!
Мама: — Ох, какая шишка!
— Две! — ответит маме мишка.

# l | autumn | animals | Белка и жёлудь
Белка жёлудь закопала,
Лапкой ямку засыпала.
Белка ищет — нет как нет!
— Где же жёлудь? Где обед?
Ахнет белка: — Вот дела!
Где же ямка? Не нашла!
Жёлудь спит под тёплым мхом —
Будет дубом. Но — потом!

# l | winter | animals | Волчонок и луна
Ночь. Зима. Волчонок Вова
Нос поднял и воет снова:
— У-у-у! Спустись, луна!
Я один, и ты одна!
Мама: — Вова, я с тобой!
Ты — малыш мой золотой!
Облака — к луне. Луна
Тоже, Вова, не одна!

# l | spring | kids | Булка пополам
Миша с булкой. Май. Лужок.
Голубь к Мише — на шажок.
Голубь ходит, голубь ждёт.
Гуль-гуль-гуль! — и не уйдёт.
Миша булку — пополам:
— Половинку — голубям!
Ой! А голуби — толпой!
Миша: — Мама! Я — домой!

# r | autumn | animals | Крот
Крот копает поутру,
Роет-роет он нору.
Вдруг — морковка! Сразу в рот:
— Хрум! Хорош подземный ход!
Дед Егор идёт во двор:
— Кто морковку ест? Где вор?
Из норы — крота макушка
И морковная верхушка!

# r | winter | fairy | Дед Мороз
Дед Мороз — румяный нос,
У него подарков воз.
Вот идёт он по двору
И дрожит, как на ветру.
Рома шарф ему несёт,
Жора — чай, а к чаю — мёд.
Пьёт Мороз — и вдруг: — Жара!
Мне в сугроб, домой пора!

# r | spring | robot | Сторож
Робот Гоша — сторож новый,
Он стоит, такой суровый,
Охраняет огород:
— Кыш, вороны! В норку, крот!
А на Гоше, на макушке,
Две вороны, как в избушке,
Строят гнёздышко с утра:
— Робот, ты — наш дом! Ура!

# r | winter | kids | Два сугроба
Горка, санки и мороз.
Красный у Егора нос.
Раз — и с горки! Ух, ура!
А внизу — сугроб-гора!
Бух! — Где Рома? Где Егор?
Нос торчит, как помидор!
Мама: — Что за два сугроба?
Марш домой, сушиться, оба!

# r | spring | bird | Грачи
Март. И трактор тарахтит,
Пашет, роет, ворошит.
А за трактором — грачи
Ходят важно, как врачи.
Дядя Жора: — Эй, сосед!
Хочешь сыра на обед?
— Гра! Грачу не нужен сыр:
Червячок — вот это пир!

# r | winter | animals | Храп
Кто храпит в бору зимой?
Хр-р-р! — дрожит сугроб горой!
— Это трактор? — Это гром?
— Нет! Под ним — медвежий дом!
Мишке снится: мёд, ромашки,
Жаркий август и букашки.
Спи, медведь, до марта, спи —
Ой, потише! Не храпи!

# r | summer | hero | Супер-Рома
Я — герой! Я — супер-Рома!
Не боюсь я даже грома!
Не боюсь я носорога,
Динозавра, осьминога!
Вдруг комар — зудит, звенит,
И герой домой бежит:
— Мама! Мама! Там комар!
Он огромный, будто шар!

# r | autumn | kids | Мухомор
Ходят Рома и Егор
Рано утром в тёмный бор.
Видят: красный, как из сказки,
Мухомор — ну как с раскраски!
— Может, в суп его возьмём?
— Нет, дружок! Мы обойдём.
Это зонтик гнома, Рома,
Гном под ним сидит, как дома.

# r | autumn | cat | Рыжик
Где ты, Рыжик? Кис-кис-кис!
Рома — на чердак и вниз.
Нет на крыше, нет в траве,
Нет у Ромы в рукаве!
Вот корзина с урожаем —
Тыквы рыжие считаем:
Раз — и два... Мур-мур! — и вот:
Между тыквами — наш кот!

# r | spring | kids | Торт
Мамин праздник! Тсс! С утра
Рома с папой — мастера:
Тесто, сахар и мука,
Нос в муке, в муке рука!
Мама ахнет: — Ну и торт!
Папа горд, и Рома горд.
А на кухне — ой-ой-ой!
Даже кот — и тот седой!

# r | summer | dog | Гроза
Гром — бабах! Гроза идёт!
Пёс Барбос — хвост под живот,
Мигом — под кровать: — Ой-ой!
Рома, Рома, ты со мной?
Рома — тоже под кровать:
— Будем вместе гром считать!
Раз и два... Гром — за горой!
— Ты, Барбос, у нас герой!

# r | summer | animals | Муравей
Муравей идёт тропой,
Тащит щепку над собой.
Рома ахнет: — Ну, дружок!
Я бы так, как ты, не смог!
Рома — к камню: — Раз-два! Ну-ка!
Ох! Ни с места! Вот так штука!
Муравей бежит себе,
Щепку тащит по тропе.
`;
