// Format (see poems-parse.js): "# <target> | <season> | <hero> | <title>", the lines, a blank line.
// target: s1 z1 s z sh zh c ch l1 l r r1 (a soft sound ends in 1) or a pair like s+sh; season: autumn winter spring summer any.
